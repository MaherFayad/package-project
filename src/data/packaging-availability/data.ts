function build(): Record<string, AvailabilityEntry> {
  const out: Record<string, AvailabilityEntry> = {};
  for (const fam of FAMILIES) {
    out[fam.slug] = fam;
    for (const [subSlug, sub] of Object.entries(SUBS[fam.slug] ?? {})) {
      const slug = `${fam.slug}/${subSlug}`;
      const merged: AvailabilityEntry = { ...fam, ...sub, slug, family: fam.slug };
      if ("priceBandEGP" in sub && sub.priceBandEGP === undefined) delete merged.priceBandEGP;
      if (sub.sources) merged.sources = [...new Set([...sub.sources, ...fam.sources])];
      out[slug] = merged;
    }
  }
  return out;
}

