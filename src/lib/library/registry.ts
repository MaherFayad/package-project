import type { BoxModelDef, ModelDef, ModelSource, VesselModelDef } from "./types";
import { MODEL_INDEX } from "./model-index.generated";

/**
 * Model registry (PERF-04). Lookups are synchronous over the models loaded so far:
 *
 * - On the server and in scripts, `@/lib/library` loads every pack eagerly and registers it, so
 *   `modelByCode` sees all models.
 * - In the browser, import from here (or `@/lib/library/doc`) and call `await loadModel(code)`
 *   (or `useLibraryModel`) before the first lookup: only that model's family pack is fetched
 *   (`import()` per family), not all 370 generators.
 *
 * `MODEL_INDEX` (generated by scripts/generate-library-index.ts, checked by a unit test) maps
 * each code to its pack and final slug, so lazy and eager loading dedupe identically.
 */

const BY_CODE = new Map<string, ModelDef>();
const BY_SLUG = new Map<string, ModelDef>();

type Pack = { models: ModelDef[] };

/** One dynamic import per family pack (code-split chunks). */
const PACK_LOADERS: Record<ModelSource, () => Promise<Pack>> = {
  core: () => import("./packs/core"),
  "fefco-02": () => import("./packs/fefco-02"),
  "fefco-03-05": () => import("./packs/fefco-03-05"),
  "fefco-04": () => import("./packs/fefco-04"),
  "fefco-06-07": () => import("./packs/fefco-06-07"),
  "fefco-09": () => import("./packs/fefco-09"),
  "ecma-tuck": () => import("./packs/ecma-tuck"),
  "ecma-specials": () => import("./packs/ecma-specials"),
  foodservice: () => import("./packs/foodservice"),
  "rigid-tubes": () => import("./packs/rigid-tubes"),
  bags: () => import("./packs/bags"),
  "vessel-core": () => import("./packs/vessel-core"),
  "vessel-bottles": () => import("./packs/vessel-bottles"),
  "vessel-cosmetic": () => import("./packs/vessel-cosmetic"),
  "vessel-flexible": () => import("./packs/vessel-flexible"),
};

/** Register already-built models (eager entry, or a loaded pack after index filtering). */
export function registerModels(list: readonly ModelDef[]): void {
  for (const m of list) {
    BY_CODE.set(m.code, m);
    BY_SLUG.set(m.slug, m);
  }
}

/** Register a pack's models the way the eager entry dedupes them (owning pack + final slug). */
function registerPack(source: ModelSource, pack: Pack): void {
  const keep: ModelDef[] = [];
  for (const m of pack.models) {
    const row = MODEL_INDEX[m.code];
    if (!row || row[0] !== source || BY_CODE.has(m.code)) continue;
    keep.push(row[1] === m.slug ? m : ({ ...m, slug: row[1] } as ModelDef));
  }
  registerModels(keep);
}

const loading = new Map<ModelSource, Promise<void>>();

function loadPack(source: ModelSource): Promise<void> {
  let p = loading.get(source);
  if (!p) {
    p = PACK_LOADERS[source]().then((pack) => registerPack(source, pack));
    loading.set(source, p);
  }
  return p;
}

/** Pack of a code, slug or code in any case (no model loaded). */
export function modelSourceOf(param: string | null | undefined): { code: string; source: ModelSource } | null {
  if (!param) return null;
  const p = decodeURIComponent(param).trim();
  for (const c of [p, p.toUpperCase(), p.toUpperCase().replace(/-/g, "_")]) {
    const row = MODEL_INDEX[c];
    if (row) return { code: c, source: row[0] };
  }
  const bySlug = SLUG_INDEX.get(p.toLowerCase());
  return bySlug ? { code: bySlug, source: MODEL_INDEX[bySlug][0] } : null;
}

const SLUG_INDEX = new Map(Object.entries(MODEL_INDEX).map(([code, [, slug]]) => [slug, code]));

/** Load (once) the family pack of a model and return it. Null for an unknown code. */
export async function loadModel(param: string | null | undefined): Promise<ModelDef | null> {
  const hit = modelSourceOf(param);
  if (!hit) return null;
  if (!BY_CODE.has(hit.code)) await loadPack(hit.source);
  return BY_CODE.get(hit.code) ?? null;
}

/** Final slug of a model code without loading its pack. */
export function modelSlugOf(code: string | null | undefined): string | null {
  return (code && MODEL_INDEX[code]?.[1]) || null;
}

export function isModelLoaded(code: string | null | undefined): boolean {
  return !!code && BY_CODE.has(code);
}

export function modelByCode(code: string | null | undefined): ModelDef | null {
  return code ? (BY_CODE.get(code) ?? null) : null;
}

/** Slug ("mailer-box"), or a code in any case ("fefco_0203", "BTL_GLASS_…"). */
export function modelFromParam(param: string): ModelDef | null {
  const p = decodeURIComponent(param).trim();
  return BY_SLUG.get(p.toLowerCase()) ?? BY_CODE.get(p) ?? BY_CODE.get(p.toUpperCase().replace(/-/g, "_")) ?? null;
}

/**
 * Every box model, loading the box family packs that are not loaded yet (one chunk per family;
 * containers are skipped). Used by the full-artwork fit search (designer: artwork fit).
 */
export async function loadBoxModels(): Promise<BoxModelDef[]> {
  const sources = (Object.keys(PACK_LOADERS) as ModelSource[]).filter((s) => !s.startsWith("vessel-"));
  await Promise.all(sources.map(loadPack));
  return Object.keys(MODEL_INDEX)
    .map((code) => BY_CODE.get(code))
    .filter((m): m is BoxModelDef => m?.kind === "box");
}

export function boxModel(code: string | null | undefined): BoxModelDef | null {
  const m = modelByCode(code);
  return m?.kind === "box" ? m : null;
}

export function vesselModel(code: string | null | undefined): VesselModelDef | null {
  const m = modelByCode(code);
  return m?.kind === "vessel" ? m : null;
}
