export const DEFINITION_BY_CODE: Record<FlexibleCode, FlexibleDefinition> = Object.fromEntries(DEFINITIONS.map((d) => [d.code, d])) as Record<FlexibleCode, FlexibleDefinition>;

export function definitionFor(code: FlexibleCode): FlexibleDefinition {
  const d = DEFINITION_BY_CODE[code];
  if (!d) throw new Error(`unknown flexible code ${code}`);
  return d;
}

/** Default options of a style, with everything it does not allow switched off. */
export function resolveOptions(code: FlexibleCode, opts: Partial<FlexOptions> = {}): FlexOptions {
  const def = definitionFor(code);
  const out: FlexOptions = { ...NO_OPTIONS, ...def.defaultOptions, ...opts };
  for (const k of ALL_OPTION_KEYS) {
    if (!def.allowedOptions.includes(k)) (out as unknown as Record<string, unknown>)[k] = NO_OPTIONS[k];
  }
  return out;
}
