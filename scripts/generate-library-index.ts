/**
 * Writes src/lib/library/model-index.generated.ts: code -> [pack, final slug] for every library
 * model, so the browser registry (src/lib/library/registry.ts) can load one family pack and
 * dedupe exactly like the eager entry. Run after adding or renaming a model:
 *   npx tsx scripts/generate-library-index.ts
 */
import fs from "node:fs";
import path from "node:path";
import { MODELS } from "../src/lib/library";

const rows = MODELS.map((m) => `  ${JSON.stringify(m.code)}: [${JSON.stringify(m.source)}, ${JSON.stringify(m.slug)}],`).join("\n");
fs.writeFileSync(
  path.resolve("src/lib/library/model-index.generated.ts"),
  `// Generated by scripts/generate-library-index.ts. Do not edit.\nimport type { ModelSource } from "./types";\n\nexport const MODEL_INDEX: Record<string, [ModelSource, string]> = {\n${rows}\n};\n`,
);
console.log(`wrote ${MODELS.length} models`);
