/**
 * Writes src/data/catalogue/order-mode-table.ts: the non-instant models (B-16) as a small static
 * table, so pricing and the designer read order modes without loading the catalogue.
 *   npx tsx scripts/generate-order-mode-table.ts
 */
import fs from "node:fs";
import path from "node:path";
import { CATALOGUE } from "../src/data/catalogue";
import { orderModeForEntry } from "../src/data/catalogue/order-mode";

const rows = CATALOGUE.map((e) => [e.code, orderModeForEntry(e)] as const).filter(([, m]) => m.mode !== "instant");
const egypt = CATALOGUE.filter((e) => e.availableInEgypt !== "local").map((e) => `  ${JSON.stringify(e.code)}: ${JSON.stringify(e.availableInEgypt)},`).join("\n");
const body = rows.map(([c, m]) => `  ${JSON.stringify(c)}: [${JSON.stringify(m.mode)}, ${JSON.stringify(m.reason)}],`).join("\n");
fs.writeFileSync(
  path.resolve("src/data/catalogue/order-mode-table.ts"),
  `// Generated by scripts/generate-order-mode-table.ts from src/data/catalogue/order-mode.ts. Do not edit.\n` +
    `export const ORDER_MODE_TABLE: Record<string, ["listed" | "quote" | "preview", "SPECIAL_GLUING" | "QUOTE_ONLY_STOCK" | "RARE_IN_EGYPT" | "FILLING_LINE"]> = {\n${body}\n};\n\n` +
    `/** Models not made locally (the rest are "local"): availability in Egypt for light client surfaces. */\n` +
    `export const EGYPT_TABLE: Record<string, "imported" | "rare"> = {\n${egypt}\n};\n`,
);
console.log(`wrote ${rows.length} non-instant models`);
