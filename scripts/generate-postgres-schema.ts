/**
 * Writes prisma/postgres/schema.prisma: the production (Cloudflare Workers + Neon) copy of
 * prisma/schema.prisma. Dev, unit tests and e2e keep SQLite; the models are identical because the
 * schema only uses types both databases support (String "enums", Json, Int piasters).
 *
 * Differences:
 *  - provider "postgresql";
 *  - engineType "client": no Rust query engine binary. The Worker connects through a driver
 *    adapter (@prisma/adapter-pg over Hyperdrive), see src/lib/db.ts.
 *
 * Run: npx tsx scripts/generate-postgres-schema.ts   (a unit test fails when the copy is stale)
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(__dirname, "..");
export const SOURCE = path.join(ROOT, "prisma", "schema.prisma");
export const TARGET = path.join(ROOT, "prisma", "postgres", "schema.prisma");

const HEADER = `// GENERATED by scripts/generate-postgres-schema.ts from prisma/schema.prisma. Do not edit.
// Production schema (PostgreSQL on Neon, reached from Cloudflare Workers through Hyperdrive).
`;

export function postgresSchema(source: string): string {
  const generator = /generator client \{[^}]*\}/;
  const datasource = /datasource db \{[^}]*\}/;
  if (!generator.test(source) || !datasource.test(source)) throw new Error("schema.prisma: generator or datasource block not found");
  const body = source
    .replace(generator, `generator client {\n  provider   = "prisma-client-js"\n  engineType = "client"\n}`)
    .replace(datasource, `datasource db {\n  provider = "postgresql"\n  url      = env("ELBA_DATABASE_URL")\n}`);
  return HEADER + body;
}

if (require.main === module) {
  fs.mkdirSync(path.dirname(TARGET), { recursive: true });
  fs.writeFileSync(TARGET, postgresSchema(fs.readFileSync(SOURCE, "utf8")));
  console.log(`wrote ${path.relative(ROOT, TARGET)}`);
}
