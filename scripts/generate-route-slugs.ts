/**
 * R5-PL-19: the slugs the middleware can check without a database, so unknown catalogue models,
 * box styles and size pages get the server-rendered 404 (src/lib/routing/static-404.ts) instead of
 * Next's client-rendered one. Writes src/lib/routing/route-slugs.generated.ts.
 *
 *   npx tsx scripts/generate-route-slugs.ts          # write (also run by `npm run build`)
 *   npx tsx scripts/generate-route-slugs.ts --check  # exit 1 if stale
 */
import fs from "node:fs";
import path from "node:path";
import { CATALOGUE } from "../src/data/catalogue";
import { STRUCTURE_SLUGS } from "../src/components/store/catalog";
import { STRUCTURE_LIST } from "../src/lib/dieline";

const ROOT = process.cwd();
const OUT = path.join(ROOT, "src/lib/routing/route-slugs.generated.ts");
const APP = path.join(ROOT, "src/app/[locale]");
const ROUTE_FILE = /^(page|route)\.(tsx?|js)$/;

/** Top-level segments (route groups flattened) that have no route below them. */
function leafSegments(): string[] {
  const tops = new Map<string, string[]>(); // segment → its directories
  const walk = (dir: string) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      if (!e.isDirectory()) continue;
      const p = path.join(dir, e.name);
      if (/^\(.*\)$/.test(e.name)) walk(p);
      else if (!e.name.startsWith("_") && !e.name.startsWith("[")) tops.set(e.name, [...(tops.get(e.name) ?? []), p]);
    }
  };
  walk(APP);
  const hasChildRoute = (dir: string): boolean =>
    fs.readdirSync(dir, { withFileTypes: true }).some((e) => {
      if (!e.isDirectory()) return false;
      const p = path.join(dir, e.name);
      if (/^\(.*\)$/.test(e.name)) return hasChildRoute(p); // a group continues the same level
      if (e.name.startsWith("_")) return false;
      const routeHere = fs.readdirSync(p).some((f) => ROUTE_FILE.test(f));
      return routeHere || hasChildRoute(p);
    });
  return [...tops].filter(([, dirs]) => !dirs.some(hasChildRoute)).map(([s]) => s).sort();
}

export function compute() {
  return {
    catalogueSlugs: [...new Set(CATALOGUE.map((e) => e.slug))].sort(),
    catalogueCodes: [...new Set(CATALOGUE.map((e) => e.code))].sort(),
    structureSlugs: [...new Set(Object.values(STRUCTURE_SLUGS))].sort(),
    catalogueRedirectSlugs: [...new Set(STRUCTURE_LIST.map((s) => s.slug))].sort(),
    leafSegments: leafSegments(),
  };
}

export function render(d: ReturnType<typeof compute>): string {
  const arr = (a: string[]) => `[\n${a.map((s) => `  ${JSON.stringify(s)},`).join("\n")}\n]`;
  return `// Generated by scripts/generate-route-slugs.ts (R5-PL-19). Do not edit; re-run the script.
/** Catalogue model slugs (/catalog/<slug>, matched lower-cased) and codes (exact or upper-cased). */
export const CATALOGUE_SLUGS: readonly string[] = ${arr(d.catalogueSlugs)};
export const CATALOGUE_CODES: readonly string[] = ${arr(d.catalogueCodes)};
/** Box style slugs (/boxes/<slug> and /boxes/<slug>/<size>). */
export const STRUCTURE_ROUTE_SLUGS: readonly string[] = ${arr(d.structureSlugs)};
/** Old /catalog/<structure> URLs that redirect to /boxes/<structure>. */
export const CATALOGUE_REDIRECT_SLUGS: readonly string[] = ${arr(d.catalogueRedirectSlugs)};
/** Top-level segments with no route below them: any deeper path is unknown. */
export const LEAF_SEGMENTS: readonly string[] = ${arr(d.leafSegments)};
`;
}

if (process.argv[1] && /generate-route-slugs/.test(process.argv[1])) {
  const next = render(compute());
  if (process.argv.includes("--check")) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
    if (cur !== next) { console.error("src/lib/routing/route-slugs.generated.ts is stale: npx tsx scripts/generate-route-slugs.ts"); process.exit(1); }
    console.log("route slugs up to date");
  } else {
    fs.writeFileSync(OUT, next);
    const d = compute();
    console.log(`catalogue ${d.catalogueSlugs.length} slugs / ${d.catalogueCodes.length} codes, structures ${d.structureSlugs.length}, redirects ${d.catalogueRedirectSlugs.length}, leaf segments ${d.leafSegments.join(", ")}`);
  }
}
